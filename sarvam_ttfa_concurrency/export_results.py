"""
Export Results - CSV Summary + Excel Report
============================================
Processes raw TTFA and concurrency logs and generates:
1. TTFA sequential summary CSV (per language)
2. Concurrency summary CSV (already generated by concurrency_test.py)
3. Final Excel report with formatted sheets and charts
"""

import os
import pandas as pd
import numpy as np

# =========================
# CONFIG
# =========================
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
os.chdir(SCRIPT_DIR)

TTFA_RAW_LOG = "logs/ttfa_raw.csv"
CONCURRENCY_LOG = "logs/concurrency_summary.csv"

TTFA_SUMMARY_CSV = "logs/ttfa_summary.csv"
FINAL_EXCEL = "sarvam_ttfa_concurrency_report.xlsx"


# =========================
# TTFA SUMMARY GENERATION
# =========================
def generate_ttfa_summary():
    """Generate per-language TTFA summary from raw logs."""

    if not os.path.exists(TTFA_RAW_LOG):
        print(f"TTFA raw log not found: {TTFA_RAW_LOG}")
        return pd.DataFrame()

    df = pd.read_csv(TTFA_RAW_LOG)
    df = df[df["status"] == "Success"].copy()

    if df.empty:
        print("No successful TTFA results found.")
        return pd.DataFrame()

    summary_rows = []

    for language in df["language"].unique():

        lang_df = df[df["language"] == language]
        ttfa_values = lang_df["ttfa_ms"]

        if len(ttfa_values) > 0:
            # TTFA metrics
            ttfa_avg = ttfa_values.mean()
            ttfa_median = ttfa_values.median()
            ttfa_p95 = ttfa_values.quantile(0.95)
            ttfa_p99 = ttfa_values.quantile(0.99)
            ttfa_std = ttfa_values.std()
            ttfa_min = ttfa_values.min()
            ttfa_max = ttfa_values.max()

            total_requests = len(lang_df)
            success_count = len(ttfa_values)
        else:
            ttfa_avg = ttfa_median = ttfa_p95 = ttfa_p99 = ttfa_std = ttfa_min = ttfa_max = 0
            total_requests = success_count = 0

        summary_rows.append({
            "language": language,
            "model": "Sarvam",
            "total_requests": total_requests,
            "successful": success_count,
            "avg_ttfa_ms": round(ttfa_avg, 2),
            "median_ttfa_ms": round(ttfa_median, 2),
            "p95_ttfa_ms": round(ttfa_p95, 2),
            "p99_ttfa_ms": round(ttfa_p99, 2),
            "std_dev_ttfa_ms": round(ttfa_std, 2),
            "min_ttfa_ms": round(ttfa_min, 2),
            "max_ttfa_ms": round(ttfa_max, 2),
        })

    summary_df = pd.DataFrame(summary_rows)
    summary_df.to_csv(TTFA_SUMMARY_CSV, index=False)
    print(f"TTFA summary saved to: {TTFA_SUMMARY_CSV}")

    return summary_df


# =========================
# EXCEL REPORT GENERATION
# =========================
def generate_excel_report(ttfa_summary_df):
    """Generate a professionally formatted Excel report."""

    print(f"\nGenerating Excel report: {FINAL_EXCEL}")

    with pd.ExcelWriter(FINAL_EXCEL, engine="xlsxwriter") as writer:

        workbook = writer.book

        # =========================
        # FORMATS
        # =========================
        title_format = workbook.add_format({
            "bold": True,
            "font_size": 14,
            "font_color": "#1F4E79",
            "bottom": 2,
        })

        header_format = workbook.add_format({
            "bold": True,
            "border": 1,
            "align": "center",
            "valign": "middle",
            "bg_color": "#D9E1F2",
            "font_color": "#1F4E79",
            "text_wrap": True,
        })

        cell_format = workbook.add_format({
            "border": 1,
            "align": "center",
            "valign": "middle",
        })

        number_format = workbook.add_format({
            "border": 1,
            "align": "center",
            "valign": "middle",
            "num_format": "0.00",
        })

        winner_format = workbook.add_format({
            "border": 1,
            "align": "center",
            "bold": True,
            "bg_color": "#C6EFCE",
            "font_color": "#006100",
        })

        best_format = workbook.add_format({
            "border": 1,
            "align": "center",
            "bold": True,
            "bg_color": "#E2EFDA",
            "font_color": "#375623",
            "num_format": "0.00",
        })

        worst_format = workbook.add_format({
            "border": 1,
            "align": "center",
            "bg_color": "#FCE4EC",
            "font_color": "#B71C1C",
            "num_format": "0.00",
        })

        section_format = workbook.add_format({
            "bold": True,
            "font_size": 12,
            "font_color": "#2E75B6",
            "bottom": 1,
        })

        # =========================================
        # SHEET 1: Executive Summary
        # =========================================
        ws_exec = workbook.add_worksheet("Executive Summary")
        ws_exec.write(0, 0, "Sarvam TTS - Performance Executive Summary", title_format)

        exec_row = 2
        # Latency Summary Table
        ws_exec.write(exec_row, 0, "Latency Performance (TTFA)", section_format)
        exec_row += 1

        if not ttfa_summary_df.empty:
            overall_avg = ttfa_summary_df["avg_ttfa_ms"].mean()
            best_lang_lat = ttfa_summary_df.loc[ttfa_summary_df["avg_ttfa_ms"].idxmin(), "language"]
            best_lat_val = ttfa_summary_df["avg_ttfa_ms"].min()

            ws_exec.write(exec_row, 0, "System Average Latency (ms)", cell_format)
            ws_exec.write(exec_row, 1, round(overall_avg, 2), number_format)
            exec_row += 1
            ws_exec.write(exec_row, 0, "Best Language for Latency", cell_format)
            ws_exec.write(exec_row, 1, best_lang_lat, winner_format)
            exec_row += 1
            
        exec_row += 1
        # Concurrency Summary Table
        ws_exec.write(exec_row, 0, "Concurrency & Scalability", section_format)
        exec_row += 1

        if os.path.exists(CONCURRENCY_LOG):
            conc_df = pd.read_csv(CONCURRENCY_LOG)
            peak_tp = conc_df["throughput"].max()
            best_lang_tp = conc_df.loc[conc_df["throughput"].idxmax(), "language"]
            
            ws_exec.write(exec_row, 0, "Peak System Throughput (req/s)", cell_format)
            ws_exec.write(exec_row, 1, round(peak_tp, 2), number_format)
            exec_row += 1
            ws_exec.write(exec_row, 0, "Best Language for Throughput", cell_format)
            ws_exec.write(exec_row, 1, best_lang_tp, winner_format)
            exec_row += 1

            # Table 1: Average Latency (TTFA) per Language
            exec_row += 2
            ws_exec.write(exec_row, 0, "Average Latency (TTFA) per Language", section_format)
            exec_row += 1

            latency_data = []
            for language in ttfa_summary_df["language"].unique():
                lang_ttfa = ttfa_summary_df[ttfa_summary_df["language"] == language].iloc[0]
                latency_data.append({
                    "Language": language,
                    "Avg Latency (ms)": round(lang_ttfa["avg_ttfa_ms"], 2),
                    "P95 Latency (ms)": round(lang_ttfa["p95_ttfa_ms"], 2)
                })

            latency_df = pd.DataFrame(latency_data)
            latency_df.to_excel(writer, sheet_name="Executive Summary", startrow=exec_row, index=False)

            # Format headers/columns for Table 1
            for col_num, col_name in enumerate(latency_df.columns):
                ws_exec.write(exec_row, col_num, col_name, header_format)
                ws_exec.set_column(col_num, col_num, 22)

            # Highlights for Table 1
            min_avg = latency_df["Avg Latency (ms)"].min()
            for row_idx in range(len(latency_df)):
                val = latency_df.iloc[row_idx]["Avg Latency (ms)"]
                fmt = cell_format if val != min_avg else best_format
                ws_exec.write(exec_row + 1 + row_idx, 1, val, fmt)
            
            exec_row += len(latency_df) + 2

            # Table 2: Optimal Concurrency per Language
            ws_exec.write(exec_row, 0, "Optimal Concurrency per Language", section_format)
            exec_row += 1

            concurrency_data = []
            for language in ttfa_summary_df["language"].unique():
                lang_conc_data = conc_df[conc_df["language"] == language]
                if not lang_conc_data.empty:
                    tp_col = "throughput" if "throughput" in lang_conc_data.columns else "throughput_req_per_sec"
                    ttfa_col = "avg_ttfa_ms" if "avg_ttfa_ms" in lang_conc_data.columns else "avg_latency_ms"
                    
                    # We define optimal as the one with best throughput while maintaining reasonable latency
                    best_tp_row = lang_conc_data.loc[lang_conc_data[tp_col].idxmax()]
                    opt_conc = int(best_tp_row["concurrency_level"])
                    peak_tp = best_tp_row[tp_col]
                else:
                    opt_conc = "N/A"
                    peak_tp = "N/A"

                concurrency_data.append({
                    "Language": language,
                    "Optimal Concurrency": opt_conc,
                    "Avg Latency (ms)": round(best_tp_row[ttfa_col], 2) if not lang_conc_data.empty else "N/A",
                    "Peak Throughput (req/s)": round(peak_tp, 2) if isinstance(peak_tp, (int, float)) else peak_tp
                })

            concurrency_df = pd.DataFrame(concurrency_data)
            concurrency_df.to_excel(writer, sheet_name="Executive Summary", startrow=exec_row, index=False)

            # Format headers/columns for Table 2
            for col_num, col_name in enumerate(concurrency_df.columns):
                ws_exec.write(exec_row, col_num, col_name, header_format)
            
            # Highlights for Table 2
            max_tp = concurrency_df[concurrency_df["Peak Throughput (req/s)"] != "N/A"]["Peak Throughput (req/s)"].max() if not concurrency_df.empty else 0
            for row_idx in range(len(concurrency_df)):
                # Throughput highlight
                val = concurrency_df.iloc[row_idx]["Peak Throughput (req/s)"]
                if isinstance(val, (int, float)) and val == max_tp:
                    ws_exec.write(exec_row + 1 + row_idx, 3, val, winner_format)
                else:
                    ws_exec.write(exec_row + 1 + row_idx, 3, val, cell_format)
                
                # Latency column format
                lat_val = concurrency_df.iloc[row_idx]["Avg Latency (ms)"]
                ws_exec.write(exec_row + 1 + row_idx, 2, lat_val, number_format)
        
            ws_exec.set_column(0, 0, 25)
            ws_exec.set_column(1, 4, 22)

        # =========================================
        # SHEET 2: Latency Analysis (TTFA)
        # =========================================
        if not ttfa_summary_df.empty:

            ttfa_summary_df.to_excel(
                writer,
                sheet_name="Latency Analysis (TTFA)",
                startrow=2,
                index=False
            )

            ws = writer.sheets["Latency Analysis (TTFA)"]
            ws.write(0, 0, "Latency Analysis - Sequential TTFA Performance", title_format)

            # Format headers
            for col_num, col_name in enumerate(ttfa_summary_df.columns):
                ws.write(2, col_num, col_name, header_format)
                ws.set_column(col_num, col_num, 20)

            # Highlight best/worst TTFA per language
            ttfa_cols = ["avg_ttfa_ms", "median_ttfa_ms", "p95_ttfa_ms", "p99_ttfa_ms",
                         "min_ttfa_ms", "max_ttfa_ms"]

            for col_name in ttfa_cols:
                if col_name in ttfa_summary_df.columns:
                    col_idx = ttfa_summary_df.columns.get_loc(col_name)
                    values = ttfa_summary_df[col_name]

                    if len(values) > 0:
                        best_idx = values.idxmin()
                        worst_idx = values.idxmax()

                        for row_idx in range(len(ttfa_summary_df)):
                            val = ttfa_summary_df.iloc[row_idx][col_name]
                            if row_idx == best_idx:
                                ws.write(row_idx + 3, col_idx, val, best_format)
                            elif row_idx == worst_idx:
                                ws.write(row_idx + 3, col_idx, val, worst_format)

            # Overall summary
            overall_start = len(ttfa_summary_df) + 5
            ws.write(overall_start, 0, "Overall Statistics", section_format)

            overall_avg = ttfa_summary_df["avg_ttfa_ms"].mean()
            best_lang = ttfa_summary_df.loc[ttfa_summary_df["avg_ttfa_ms"].idxmin(), "language"]
            worst_lang = ttfa_summary_df.loc[ttfa_summary_df["avg_ttfa_ms"].idxmax(), "language"]

            ws.write(overall_start + 1, 0, "Overall Avg TTFA (ms)", cell_format)
            ws.write(overall_start + 1, 1, round(overall_avg, 2), number_format)

            ws.write(overall_start + 2, 0, "Best Language (Lowest TTFA)", cell_format)
            ws.write(overall_start + 2, 1, best_lang, winner_format)

            ws.write(overall_start + 3, 0, "Worst Language (Highest TTFA)", cell_format)
            ws.write(overall_start + 3, 1, worst_lang, worst_format)

            ws.freeze_panes(3, 0)


        # =========================================
        # SHEET 3: Concurrency Summary
        # =========================================
        if os.path.exists(CONCURRENCY_LOG):

            conc_df = pd.read_csv(CONCURRENCY_LOG)

            conc_df.to_excel(
                writer,
                sheet_name="Concurrency Analysis",
                startrow=12,
                index=False
            )

            ws_conc = writer.sheets["Concurrency Analysis"]
            ws_conc.write(0, 0, "Concurrency & Scalability Analysis", title_format)

            # Table 1: Per-Language Peak Performance Analysis
            ws_conc.write(3, 0, "Per-Language Peak Performance Analysis", section_format)
            ws_conc.freeze_panes(14, 0)

            analysis_rows = []
            for language in conc_df["language"].unique():
                lang_data = conc_df[conc_df["language"] == language]
                
                ttfa_col = "avg_ttfa_ms" if "avg_ttfa_ms" in conc_df.columns else "avg_latency_ms"
                tp_col = "throughput" if "throughput" in conc_df.columns else "throughput_req_per_sec"

                best_ttfa_row = lang_data.loc[lang_data[ttfa_col].idxmin()]
                best_tp_row = lang_data.loc[lang_data[tp_col].idxmax()]

                analysis_rows.append({
                    "language": language,
                    "optimal_concurrency": int(best_ttfa_row["concurrency_level"]),
                    "best_latency_ms": round(best_ttfa_row[ttfa_col], 2),
                    "peak_throughput_req_s": round(best_tp_row[tp_col], 2),
                })

            analysis_df = pd.DataFrame(analysis_rows).rename(columns={
                "language": "Language",
                "optimal_concurrency": "Optimal Concurrency",
                "best_latency_ms": "Avg Latency (ms)",
                "peak_throughput_req_s": "Peak Throughput (req/s)"
            })
            analysis_df.to_excel(
                writer,
                sheet_name="Concurrency Analysis",
                startrow=4,
                index=False
            )

            for col_num, col_name in enumerate(analysis_df.columns):
                ws_conc.write(4, col_num, col_name, header_format)
                ws_conc.set_column(col_num, col_num, 24)

            # Clearer Section Break
            ws_conc.write(11, 0, "Detailed Benchmark Tiers (Scalability Performance)", section_format)
            
            # Map technical column names to human readable versions and select performance ones
            conc_df_clean = conc_df.rename(columns={
                "language": "Language",
                "concurrency_level": "Concurrency",
                "total": "Total Req",
                "avg_ttfa_ms": "Avg Latency (ms)",
                "avg_latency_ms": "Avg Latency (ms)",
                "p50": "P50 (ms)",
                "p95": "P95 (ms)",
                "p99": "P99 (ms)",
                "throughput": "Throughput (req/s)",
                "throughput_req_per_sec": "Throughput (req/s)"
            })
            
            # Remove success/failure columns
            cols_to_keep = ["Language", "Concurrency", "Total Req", "Avg Latency (ms)", "P50 (ms)", "P95 (ms)", "P99 (ms)", "Throughput (req/s)"]
            conc_df_clean = conc_df_clean[[c for c in cols_to_keep if c in conc_df_clean.columns]]

            conc_df_clean.to_excel(
                writer,
                sheet_name="Concurrency Analysis",
                startrow=12,
                index=False
            )

            for col_num, col_name in enumerate(conc_df_clean.columns):
                ws_conc.write(12, col_num, col_name, header_format)
                ws_conc.set_column(col_num, col_num, 18) # Better column widths

        # Excel report saved handled by context manager closing

    print(f"Excel report saved: {FINAL_EXCEL}")


# =========================
# MAIN
# =========================
if __name__ == "__main__":

    print("=" * 60)
    print("  Sarvam TTS - Export Results")
    print("=" * 60)

    # Step 1: Generate TTFA summary CSV
    ttfa_summary = generate_ttfa_summary()

    # Step 2: Generate Excel report
    generate_excel_report(ttfa_summary)

    print("\nDone! Generated files:")
    print(f"  1. {TTFA_SUMMARY_CSV}")
    if os.path.exists(CONCURRENCY_LOG):
        print(f"  2. {CONCURRENCY_LOG}")
    print(f"  3. {FINAL_EXCEL}")
